/**
 * Boundary features without an ISO id, by their Natural Earth name. They map onto the country they
 * belong to under ISO 3166 (Northern Cyprus counts as Cyprus, Somaliland as Somalia); Kosovo has no
 * ISO code and uses the widely used user-assigned XK. Everything else without an id (Siachen
 * Glacier, the Indian Ocean Territories) is not a country and is left out.
 */
const CODE_BY_FEATURE_NAME: Readonly<Record<string, string>> = {
  Kosovo: 'XK',
  'N. Cyprus': 'CY',
  Somaliland: 'SO',
}

const NAMES: ReadonlyMap<string, string> = new Map([...ROWS.map(([, code, name]) => [code, name] as const), ['XK', 'Kosovo']])
const CODE_BY_NUMERIC: ReadonlyMap<string, string> = new Map(ROWS.map(([numeric, code]) => [numeric, code]))

/** The alpha-2 code of a boundary feature (its numeric id, else its name), or null when it is no country. */
export function featureCode(id: string | number | undefined, name: string | undefined): string | null {
  if (id !== undefined && id !== '') return CODE_BY_NUMERIC.get(String(id).padStart(3, '0')) ?? null
  return (name !== undefined && CODE_BY_FEATURE_NAME[name]) || null
}

/** The common English name of an upper-case alpha-2 code ("CZ" → "Czechia"); the code itself when unknown. */
export function countryName(code: string): string {
  return NAMES.get(code) ?? code
}
